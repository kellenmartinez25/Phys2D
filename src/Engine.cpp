#include <vector>
#include <unordered_map>

std::unordered_map<PhysObjectPair, Manifold, PairHash> manifoldCache;

Engine::Engine(GLFWwindow* win, Renderer* renderer) :
	WIDTH(8),
	HEIGHT(6),
	view_x(800),
	view_y(600),
	renderer(renderer),
	window(win),
	objects(1)
{

}
Engine::Engine() :
	WIDTH(8),
	HEIGHT(6),
	view_x(800),
	view_y(600)
{}
// add a physobject to the simulation
void Engine::addObject(PhysObject* obj)
{
	objects.push_back(*obj);
}
void Engine::reset() {
	objects.clear();
}
// make sure an object doesnt go off screen bounds
void Engine::pushIntoScreenBounds(PhysObject& obj) {
	// also keep within screen boundaries
	if (obj.pos.y + obj.size.y > HEIGHT) {
		obj.pos.y = HEIGHT - obj.size.y;
		obj.velocity.y *= -1.0f;
	}
	else if (obj.pos.y <= 0.0f) {
		obj.pos.y = 0.0f;
		obj.velocity.y *= -1.0f;
	}
	if (obj.pos.x + obj.size.x > WIDTH) {
		obj.pos.x = WIDTH - obj.size.x;
		obj.velocity.x *= -1.0f;
	}
	else if (obj.pos.x < 0.0f) {
		obj.pos.x = 0.0f;
		obj.velocity.x *= -1.0f;
	}
}


// update positions and velocities
void Engine::updateSim(double dt) {

	// Iterate through each object
	// generate a pair of each object to test upon:
	std::vector<std::pair<PhysObject&, PhysObject&>> pairs;
	// pair each object with one another
	for (int i = 0; i < objects.size(); i++) {
		for (int j = i + 1; j < objects.size(); j++) {
			pairs.emplace_back(objects[i], objects[j]);
		}
	}
	// the contact manifolds we will generate
	std::vector<Manifold> manifolds;
	// iterate through each pair
	for (auto& p : pairs) {
		// the new manifold
		Manifold m;
		// generate the contact manifold, might be 0 objects.
		genManifold(p.first, p.second, m);

		// dont bother processing ones with no contacts
		if (m.count == 0) continue;

		// create pair to lookup
		PhysObjectPair pp(MakePair(&p.first, &p.second));
		// try to lookup this pair's previously generated manifold
		auto iter = manifoldCache.find(pp);
		if (iter != manifoldCache.end()) {
			// get the previous manifold generated by this pair
			Manifold& oldM = iter->second;
			const double dist_threshold = .05;
			// loop through the contact points, and try to find the point of the old manifold which is the closest to the new one's point
			for (int i = 0; i < m.count; i++) {
				// the best match
				ContactPoint* best = nullptr;
				double bestDist = DBL_MAX;
				// iterate over old manifold
				for (int j = 0; j < oldM.count; j++) {
					// find the distance, and get new minimum
					double dist = glm::length(m.points[i].pos - oldM.points[j].pos);
					if (dist < bestDist) {
						bestDist = dist;
						best = &oldM.points[j];
					}
				}
				// if we found a best, and if its within the threshold then we can copy the normImpulse
				if (best && bestDist < dist_threshold &&
					glm::dot(m.normal, oldM.normal) > 0.95) {
					m.points[i].normImpulse = best->normImpulse;
					m.points[i].tangentImpulse = best->tangentImpulse;
				}
				else {
					m.points[i].normImpulse = 0.0;
					m.points[i].tangentImpulse = 0.0;
				}
			}
		}
		// push the new manifold to our manifold list
		manifolds.push_back(m);
	}
	// integrate forces
	for (auto& obj : objects) {
		obj.preUpdate(dt);
	}
	// prestep
	for (auto& m : manifolds) {
		preStep(m);
	}

	// solve collisions
	const int iterations = 8;
	for (int i = 0; i < iterations; i++) {
		for (auto& m : manifolds) {
			// collide on each manifold
			collide2D(m, dt);
		}
	}
	// apply positional correction
	for (auto& m : manifolds) {
		correctPos(m);
	}

	// reset the cache and update with the newly generated manifolds and its corresponding pair of objects
	manifoldCache.clear();
	for (auto& m : manifolds) {
		PhysObjectPair newPair = MakePair(m.A, m.B);
		manifoldCache[newPair] = m;
	}

	// update each object with new values
	for (auto& obj : objects) {
		obj.update(dt);
		// push the object into the bounds of the display
		pushIntoScreenBounds(obj);
		obj.render(renderer);
	}

	// debug drawing
	for (auto& m : manifolds) {
		for (int i = 0; i < m.count; i++) {
			DebugDraw::get().drawPoint(
				m.points[i].pos,
				glm::vec3(1.0f, 0.0f, 0.0f)
			);
		}
	}
	
}
